// Load the shared Google tag once, keeping the existing Consent Mode v2 defaults.
const analyticsInlineScript = (() => {
  if (!GA4_ID && !ADS_ID) return null;
  const ids = [GA4_ID, ADS_ID].filter(Boolean) as string[];
  const configs = ids.map((id) => `gtag('config', '${id}', { anonymize_ip: true });`).join("\n");
  const src = `https://www.googletagmanager.com/gtag/js?id=${ids[0]}`;
  return `window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}
gtag('consent','default',{ad_storage:'denied',analytics_storage:'denied',ad_user_data:'denied',ad_personalization:'denied',wait_for_update:500});
gtag('js', new Date());
${configs}
var s=document.createElement('script');s.async=true;s.src='${src}';document.head.appendChild(s);`;
})();

